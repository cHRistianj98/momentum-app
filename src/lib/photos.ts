/** Grupy miniaturek; nazwa w bieżącym języku (getter — tekst liczony przy odczycie, nie przy imporcie). */
export const PHOTO_GROUPS=GROUPS.map(({id,label})=>({id,get label(){return text(label);}}));
/**
 * Miniaturki: `title` i `groupLabel` w bieżącym języku (gettery), `titles` — tytuł w obu językach,
 * `keywords` — tytuł i nazwa grupy po polsku i po angielsku (wyszukiwanie działa w obu językach).
 */
export const PHOTO_OPTIONS=GROUPS.flatMap(group=>group.titles.map(([pl,en],index)=>{
  const titles:Localized={pl,en};
  return {
    id:`${group.id}-${String(index+1).padStart(2,'0')}`,
    src:`/assets/thumbs/${group.id}-${String(index+1).padStart(2,'0')}.webp`,
    group:group.id,
    get groupLabel(){return text(group.label);},
    get title(){return text(titles);},
    titles,
    keywords:`${pl} ${en} ${group.label.pl} ${group.label.en}`,
  };
}));
